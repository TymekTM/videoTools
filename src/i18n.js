var _currentLang = localStorage.getItem('app-lang') || 'pl';

function t(key, fallback) {
  var dict = LANGS[_currentLang] || LANGS['pl'];
  var val = dict[key];
  if (val !== undefined) return val;
  val = LANGS['pl'][key];
  if (val !== undefined) return val;
  return fallback || key;
}

function currentLang() {
  return _currentLang;
}

function setLang(lang) {
  if (!LANGS[lang]) return;
  _currentLang = lang;
  localStorage.setItem('app-lang', lang);
  document.documentElement.lang = lang;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    var val = t(key);
    if (!val) return;
    if (el.children.length > 0) {
      var last = el.childNodes[el.childNodes.length - 1];
      if (last && last.nodeType === 3) {
        last.textContent = val;
      } else {
        el.appendChild(document.createTextNode(val));
      }
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-placeholder');
    var val = t(key);
    if (val) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-title');
    var val = t(key);
    if (val) el.title = val;
  });
  document.querySelectorAll('[data-i18n-label]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-label');
    var val = t(key);
    if (!val) return;
    var firstChild = el.firstChild;
    if (firstChild && firstChild.nodeType === 3) {
      firstChild.textContent = val + ' ';
    } else {
      el.insertBefore(document.createTextNode(val + ' '), el.firstChild);
    }
  });
  document.querySelectorAll('[data-i18n-inner]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-inner');
    var val = t(key);
    if (val) el.innerHTML = val;
  });
  document.title = t('appTitle');
}
